// Pulls track data out of the untitled.stream embeds referenced in canvas_ver/index.html
// and writes it back into the page between the untitled:start / untitled:end markers.
// The site plays these files with its own player, so re-run this after you upload:
//   node build-untitled.js
//
// If a project is ever unreachable, its old block is kept rather than dropped — the
// page falls back to untitled's iframe for any project that has no data here.
const fs = require("fs");
const path = require("path");

const PAGE = path.join(__dirname, "canvas_ver", "index.html");
const START = "/* untitled:start";
const END = "/* untitled:end */";

async function project(id) {
  const res = await fetch(`https://untitled.stream/embed/${id}`, {
    headers: { "user-agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)" },
  });
  if (!res.ok) throw new Error(`${id}: HTTP ${res.status}`);
  const html = await res.text();

  const m = html.match(/window\.__remixContext\s*=\s*(\{[\s\S]*?\});\s*<\/script>/);
  if (!m) throw new Error(`${id}: no remix payload — the embed page changed shape`);

  const node = JSON.parse(m[1]).state.loaderData["routes/library.project.$projectSlug"];
  if (!node) throw new Error(`${id}: not a project embed`);

  const tracks = (node.tracks || [])
    .filter(t => t.audio_fallback_url)
    .map(t => ({ t: t.title, d: Math.round(t.duration || 0), src: t.audio_fallback_url }));

  if (!tracks.length) throw new Error(`${id}: no playable tracks`);
  return { title: node.project?.project?.title || "", tracks };
}

(async () => {
  const page = fs.readFileSync(PAGE, "utf8");
  const ids = [...new Set([...page.matchAll(/untitled\.stream\/embed\/([A-Za-z0-9_-]+)/g)].map(m => m[1]))];
  if (!ids.length) return console.log("no untitled embeds referenced — nothing to do");

  const out = {};
  for (const id of ids) {
    try {
      out[id] = await project(id);
      console.log(`  ${id}  ${out[id].tracks.length} tracks  ${out[id].title}`);
    } catch (e) {
      console.error(`  ${id}  SKIPPED — ${e.message}`);
    }
  }
  if (!Object.keys(out).length) return console.error("nothing fetched; page left alone");

  const i = page.indexOf(START), j = page.indexOf(END);
  if (i < 0 || j < 0) throw new Error("markers missing from canvas_ver/index.html");

  const block =
    `${START} — generated by build-untitled.js, do not edit by hand.\n` +
    `   Re-run \`node build-untitled.js\` after uploading to untitled.stream. */\n` +
    `const UNTITLED = ${JSON.stringify(out)};\n` +
    END;

  fs.writeFileSync(PAGE, page.slice(0, i) + block + page.slice(j + END.length));
  console.log(`wrote ${Object.keys(out).length} projects into canvas_ver/index.html`);
})();
